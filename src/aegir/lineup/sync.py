"""``aegir.lineup sync`` — SHARE: publish the materialized ontology Data Product to the
``corpora`` (sdg-corpora) submodule, the reasoner-gated know→share boundary.

``build`` materializes the products locally (what we KNOW, the gitignored ``build/dev``
projection); ``sync`` publishes the ontology Data Product to the SHARE tier — the
``corpora`` submodule, which is attribution-clean and public. It regenerates, from the live
ontology SoT (``src/aegir/ontology``), the shared artifacts under ``corpora/``:

  • ontology/   — catalog mirror (the derived catalog file(s), incl. the ``broader``
                  subsumption hierarchy) + sdg-vocab.ttl + SLOT_DSL.md
  • vocabulary/ — SKOS ConceptScheme + Atelier ReferenceCategory annotations (build_skos_vocab)
  • ddl/        — the ontology→SQL DDL spine (build_ddl_spine)

Gate: TWO ANDed checks — (1) the ontology schema-CI (``check_ontology_schema`` — TTL
well-formedness, labels/definitions, BFO ancestry, SPARQL totality); (2) the OQuaRE
ontology-quality gate (``ontology_oquare`` — a hard floor on the realized OWL: aggregate
≥3.5 AND Functional-Adequacy ≥3.0, forcing definitional rigor + BFO discipline). A broken
or sub-rigor ontology is never published. OQuaRE consumes the upstream HermiT verdict from
the realizer's certificate (JVM-free; the consistency gate is applied upstream, at
hierarchy-authoring time, by ``mediate_hierarchy``).

The content Data Product (``corpora/corpus`` — the generated chapters) is NOT touched here:
it is regenerated by the generation pipeline, not derived from the catalog.

``--commit`` commits the corpora submodule locally; ``--push`` publishes it to the shared
``zndx/sdg-corpora`` remote (the external share — explicit, never implicit). Default is a
dry materialization + diff so the change can be reviewed first.
"""
from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
SRC_ONTO = REPO / "src" / "aegir" / "ontology"
CORPORA = REPO / "corpora"


def _sh(cmd: list[str], cwd: Path = REPO) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True)


def _last(out: str, default: str = "") -> str:
    lines = [ln for ln in (out or "").splitlines() if ln.strip()]
    return lines[-1] if lines else default


def _gate() -> bool:
    """Publish gate — refuse to publish a structurally broken OR sub-rigor ontology. Two ANDed checks:

      1. schema-CI (`check_ontology_schema`) — TTL well-formedness, labels/definitions, BFO ancestry,
         SPARQL totality. Gates the CATALOG (the templates).
      2. OQuaRE (`ontology_oquare`) — the hard ontology-quality floor on the realized OWL: aggregate ≥3.5
         AND Functional-Adequacy ≥3.0, forcing definitional rigor + BFO discipline before the ontology
         Data Product is shared. Consumes the upstream HermiT verdict from HERMIT_CERTIFICATE.md (JVM-free;
         the reasoner gate stays upstream). Fail-closed if the realized OWL is absent (rebuild it first).
    """
    r = _sh([sys.executable, "scripts/check_ontology_schema.py"])
    print("   schema-CI: " + _last(r.stdout, "(no output)"))
    schema_ok = r.returncode == 0
    if not schema_ok:
        print("   schema-CI FAILED.\n" + (r.stdout or r.stderr or "")[-400:])

    owl = CORPORA / "ontology" / "sdg-ontology.owl"
    cert = CORPORA / "ontology" / "HERMIT_CERTIFICATE.md"
    if owl.exists():
        oq = _sh([sys.executable, "scripts/ontology_oquare.py", str(owl), "--certificate", str(cert)])
        print("   OQuaRE:    " + _last(oq.stdout, "(no output)"))
        oq_ok = oq.returncode == 0
        if not oq_ok:
            print((oq.stdout or oq.stderr or "")[-500:])
    else:
        print(f"   OQuaRE:    ⊘ no realized OWL at {owl.relative_to(REPO)} — run build_realized_ontology.py first")
        oq_ok = False  # the ontology Data Product includes the realized OWL — never publish it ungated

    if not (schema_ok and oq_ok):
        print("   GATE FAILED — refusing to publish.")
    return schema_ok and oq_ok


def _mirror_ontology() -> None:
    dst = CORPORA / "ontology"
    (dst / "catalog").mkdir(parents=True, exist_ok=True)
    n = 0
    live = set()
    from aegir.ontology.schema import catalog_files
    for f in catalog_files(SRC_ONTO / "catalog"):
        shutil.copy2(f, dst / "catalog" / f.name)
        live.add(f.name)
        n += 1
    # retired/renamed catalog files leave the mirror too (incl. the 0*-era family names)
    for stale in sorted(list((dst / "catalog").glob("0[1-8]_*.json"))
                        + list((dst / "catalog").glob("catalog.json"))):
        if stale.name not in live:
            stale.unlink()
            print(f"   mirror: dropped retired catalog {stale.name}")
    for name in ("sdg-vocab.ttl", "SLOT_DSL.md"):  # family_complex.json retired (pre-wired gate → measured stat)
        src = SRC_ONTO / name
        if src.exists():
            shutil.copy2(src, dst / name)
    (dst / "family_complex.json").unlink(missing_ok=True)  # drop the retired artifact from the mirror
    print(f"   mirrored {n} catalog file(s) + sdg-vocab.ttl + SLOT_DSL.md")


def _regen_vocabulary() -> bool:
    r = _sh([sys.executable, "scripts/build_skos_vocab.py", "--out", str(CORPORA / "vocabulary")])
    print("   " + _last(r.stdout, "(SKOS build produced no output)"))
    if r.returncode != 0:
        print("   SKOS build FAILED:\n" + (r.stderr or "")[-400:])
    return r.returncode == 0


def _regen_ddl() -> bool:
    """Regenerate the DDL spine, IDEMPOTENTLY. build_ddl_spine's <run_id> is a content hash of
    the catalog, so an unchanged ontology yields the same run_id. The parquet/manifest bytes are
    NOT byte-stable run-to-run (parquet metadata + manifest timestamp), so we build into a temp,
    and only swap into corpora/ddl when the run_id actually changed — otherwise keep the committed
    bytes so a no-op sync produces no spurious corpora commit."""
    import tempfile
    out = CORPORA / "ddl"
    out.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix="ddl_spine_"))
    try:
        r = _sh([sys.executable, "scripts/build_ddl_spine.py", "--output-dir", str(tmp)])
        if r.returncode != 0:
            print("   DDL spine FAILED:\n" + (r.stderr or "")[-400:])
            return False
        runs = [d for d in tmp.iterdir() if d.is_dir()]
        if not runs:
            print("   DDL spine produced no run dir")
            return False
        new_run = runs[0]
        existing = out / new_run.name
        if existing.exists():
            print(f"   DDL spine unchanged (run {new_run.name}) — kept committed bytes (idempotent)")
            return True
        for d in out.iterdir():                # catalog changed → new run_id: drop stale runs, swap in
            if d.is_dir():
                shutil.rmtree(d)
        shutil.move(str(new_run), str(existing))
        print(f"   DDL spine rebuilt → run {new_run.name}")
        return True
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def run(args=None) -> int:
    commit = bool(getattr(args, "commit", False))
    push = bool(getattr(args, "push", False))
    print("aegir.lineup sync — SHARE: ontology Data Product → corpora (sdg-corpora)")
    if not CORPORA.exists() or not (CORPORA / ".git").exists():
        print(f"  corpora submodule not checked out at {CORPORA} — `git submodule update --init`.")
        return 1

    print("1) reasoner/schema gate (check_ontology_schema)")
    if not _gate():
        return 1
    print("2) mirror ontology SoT → corpora/ontology/")
    _mirror_ontology()
    print("3) regenerate SKOS vocabulary → corpora/vocabulary/")
    _regen_vocabulary()
    print("4) regenerate DDL spine → corpora/ddl/")
    _regen_ddl()

    st = _sh(["git", "status", "--short"], cwd=CORPORA)
    changed = bool((st.stdout or "").strip())
    print("5) corpora working-tree diff:")
    print((st.stdout or "").rstrip() if changed else "   (no working-tree changes — ontology already in sync)")

    # (a) commit any regen changes from THIS run
    if changed:
        if not (commit or push):
            print("done — regenerated in the working tree (not committed).\n"
                  "  review the diff, then re-run with --commit (and --push to publish to zndx/sdg-corpora).")
            return 0
        _sh(["git", "add", "-A"], cwd=CORPORA)
        msg = "Re-sync ontology Data Product from aegir SoT (catalog incl. broader hierarchy + SKOS + DDL)"
        c = _sh(["git", "commit", "-m", msg], cwd=CORPORA)
        print("   corpora commit: " + _last(c.stdout + c.stderr, "(commit produced no output)"))

    # (b) push is BRANCH-WIDE — publishes every pending commit (this run's regen AND any other
    #     unpushed corpora work, e.g. the corpus collections committed out-of-band), not just what
    #     this run regenerated. `git push` is a no-op ("Everything up-to-date") when nothing pends.
    if push:
        ahead = _last((_sh(["git", "rev-list", "--count", "@{u}..HEAD"], cwd=CORPORA).stdout or "").strip())
        p = _sh(["git", "push"], cwd=CORPORA)
        print(f"   push ({ahead or '?'} pending): " + _last(p.stderr + p.stdout, "ok"))
        print("   NOTE: if corpora HEAD moved, bump the aegir submodule pointer (git add corpora && commit).")
    elif changed and commit:
        print("   committed locally; NOT pushed — re-run with --push to publish to zndx/sdg-corpora.")
    elif not changed:
        print("done — corpora already in sync; nothing to push (re-run with --push if there are "
              "unpushed commits to publish).")
    return 0
